import { readdir, readFile, writeFile } from 'node:fs/promises';
import { basename, join, resolve } from 'node:path';

/** Bundle inputs are generated from locale files; translators never edit an import registry. */
export async function generateLocales(i18n = resolve(import.meta.dir, '../packages/core/src/i18n')): Promise<void> {
  const files = (await readdir(join(i18n, 'strings'), { withFileTypes: true }))
    .filter(entry => entry.isFile() && entry.name.endsWith('.json')).map(entry => entry.name).sort();
  const imports = files.map((file, i) => `import catalog${i} from ${JSON.stringify(`./strings/${file}`)};`);
  const entries = files.map((file, i) => `  ${JSON.stringify(basename(file, '.json'))}: catalog${i},`);
  const source = `// Generated by tools/locales.ts from strings/*.json.\n${imports.join('\n')}\n\nexport const catalogs: Record<string, Record<string, string>> = {\n${entries.join('\n')}\n};\n`;
  const out = join(i18n, 'catalogs.ts');
  let current = ''; try { current = await readFile(out, 'utf8'); } catch (e) { if ((e as NodeJS.ErrnoException).code !== 'ENOENT') throw e; }
  if (current !== source) await writeFile(out, source);
}
if (import.meta.main) await generateLocales();
