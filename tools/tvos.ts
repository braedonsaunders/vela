/**
 * Build Vela for Apple TV and install it on one, from a staged copy of this checkout:
 *
 *   VELA_TV_ORIGIN=https://<ether> bun tools/tvos.ts [--device <udid|name>] [--run] [--release] [--sim]
 *
 * The client (tracked and untracked files) is staged on the scratch drive (vela-build/tvos/stage) and built with
 * Exact's Apple host (`exact.mjs ios --tvos`): the data module and the renderer run natively,
 * and modules/apple/*.swift supplies the native views (the player above all). The staged
 * copy gains what a checkout never holds: VelaMedia.xcframework (FFmpeg, LGPL, built by
 * native/apple/media/build-ffmpeg.sh into the scratch drive) and VelaOrigin.swift, the Ether
 * this build signs in to. The checkout is never touched.
 */
import { cp, mkdir, readdir, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { existsSync, realpathSync, statSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { generateLocales } from './locales';

const root = resolve(import.meta.dir, '..');
const args = process.argv.slice(2);
const flag = (name: string) => args.includes(name);
const value = (name: string) => { const at = args.indexOf(name); return at >= 0 ? args[at + 1] : undefined; };
const origin = process.env.VELA_TV_ORIGIN ?? '';
if (!/^https?:\/\/[^/?#]+$/.test(origin)) throw new Error('Set VELA_TV_ORIGIN to the Ether origin this build signs in to (https://host:port, no path)');
const simulator = flag('--sim');
const developer = process.env.DEVELOPER_DIR ?? '/Applications/Xcode.app/Contents/Developer';
// Exact opens a static app's files without following any symlink, from the root down: the
// stage is a real path (the scratch drive's, resolved) and holds no links of its own.
const scratch = realpathSync(join(homedir(), '.scratch')) + '/vela-build/tvos';
const stage = join(scratch, 'stage');

// 1. Stage the client and protocol, as tools/check.ts does, keeping the build's caches.
const git = Bun.spawnSync(['git', 'ls-files', '-co', '--exclude-standard', '-z', '--', 'client', 'protocol'], { cwd: root });
await mkdir(join(stage, 'client'), { recursive: true });
for (const entry of await readdir(join(stage, 'client'))) if (entry !== '.exact' && entry !== 'target') await rm(join(stage, 'client', entry), { recursive: true, force: true });
await rm(join(stage, 'protocol'), { recursive: true, force: true });
for (const path of git.stdout.toString().split('\0').filter(p => p && !p.includes('node_modules') && !p.startsWith('client/target') && !p.startsWith('client/.exact') && p !== 'client/wire')) {
  const from = join(root, path), to = join(stage, path);
  await mkdir(dirname(to), { recursive: true });
  await cp(from, to, { recursive: true, dereference: true }).catch(() => {});
}
await rm(join(stage, 'vendor/exact'), { force: true });
await mkdir(join(stage, 'vendor'), { recursive: true });
await symlink(realpathSync(join(root, 'vendor/exact')), join(stage, 'vendor/exact'));
const client = join(stage, 'client');

// 2. While compiled skins exist, a native build carries one engine: the document renderer.
if (existsSync(join(root, 'tools/engine.ts'))) {
  const { prepareEngine } = await import('./engine');
  await prepareEngine(client, 'doc');
}
await generateLocales(client);

// 3. FFmpeg (LGPL) and the Vela shim, built once into the scratch drive.
const media = join(scratch, 'media-out');
const env = { ...process.env, DEVELOPER_DIR: developer, ...(simulator ? { VELA_MEDIA_SIMULATOR: '1' } : {}) };
const shim = ['vela_media.c', 'vela_media.h', 'build-ffmpeg.sh'].map(f => statSync(join(root, 'native/apple/media', f)).mtimeMs);
const builtAt = existsSync(join(media, 'VelaMedia.xcframework/Info.plist')) ? statSync(join(media, 'VelaMedia.xcframework/Info.plist')).mtimeMs : 0;
if (builtAt < Math.max(...shim) || simulator && !existsSync(join(media, 'VelaMedia.xcframework/tvos-arm64-simulator'))) {
  const built = Bun.spawnSync(['sh', join(root, 'native/apple/media/build-ffmpeg.sh'), media], { env, stdout: 'inherit', stderr: 'inherit' });
  if (built.exitCode) process.exit(built.exitCode);
}
await cp(join(media, 'VelaMedia.xcframework'), join(client, 'modules/apple/VelaMedia.xcframework'), { recursive: true, verbatimSymlinks: true });

// 4. The server this build signs in to.
await writeFile(join(client, 'modules/apple/VelaOrigin.swift'),
  `// Generated by tools/tvos.ts: the Ether this build signs in to.\nlet velaBuildOrigin = ${JSON.stringify(origin)}\n`);

// 5. Build with Exact's Apple host. A device bundle is built --unsigned and signed here:
// Exact's device signing accepts only iOS profiles, so it refuses the team's tvOS profile.
const device = value('--device') ?? process.env.EXACT_PHONE ?? '';
const build = ['exact.mjs', 'ios', '--tvos', ...(simulator ? (flag('--run') ? ['--run'] : []) : ['--device', '--unsigned', '--json']), ...(flag('--release') ? ['--release'] : [])];
const built = Bun.spawnSync([process.execPath, ...build], {
  cwd: client, stdout: simulator ? 'inherit' : 'pipe', stderr: 'inherit',
  env: { ...env, ...(value('--sim-name') ? { EXACT_SIM: value('--sim-name')! } : {}) },
});
if (built.exitCode || simulator) process.exit(built.exitCode ?? 1);
const report = JSON.parse(built.stdout.toString().trim().split('\n').at(-1) ?? '{}') as { path?: string };
if (!report.path) throw new Error('exact.mjs ios --json named no bundle');
const bundle = report.path;

// 6. Sign for the Apple TV with an installed tvOS development profile that covers it.
const sh = (cmd: string[], input?: string) => {
  const r = Bun.spawnSync(cmd, { env, stdin: input === undefined ? 'ignore' : Buffer.from(input) });
  if (r.exitCode) throw new Error(`${cmd.slice(0, 3).join(' ')} failed: ${r.stderr.toString().trim()}`);
  return r.stdout.toString();
};
const udid = (() => {
  const list = JSON.parse(sh(['sh', '-c', 'xcrun devicectl list devices --json-output /dev/stdout -q 2>/dev/null'])) as { result: { devices: { identifier: string; hardwareProperties: { udid: string; deviceType: string }; deviceProperties: { name: string } }[] } };
  const tvs = list.result.devices.filter(d => d.hardwareProperties.deviceType === 'appleTV');
  const found = tvs.find(d => !device || d.hardwareProperties.udid === device || d.deviceProperties.name === device || d.identifier === device) ;
  if (!found) throw new Error(`no Apple TV ${device} (xcrun devicectl list devices)`);
  return found.hardwareProperties.udid;
})();
const appId = JSON.parse(await readFile(join(client, 'app.json'), 'utf8')).app.id as string;
const chosen = JSON.parse(sh(['python3', '-I', '-c', `
import plistlib, subprocess, sys, os, glob, hashlib, json, datetime
udid, bundle = sys.argv[1], sys.argv[2]
ids = subprocess.run(['security', 'find-identity', '-v', '-p', 'codesigning'], capture_output=True, text=True).stdout
best = None
for path in glob.glob(os.path.expanduser('~/Library/Developer/Xcode/UserData/Provisioning Profiles/*.mobileprovision')) + glob.glob(os.path.expanduser('~/Library/MobileDevice/Provisioning Profiles/*.mobileprovision')):
    p = plistlib.loads(subprocess.run(['security', 'cms', '-D', '-i', path], capture_output=True).stdout)
    e = p.get('Entitlements', {})
    prefix = p.get('ApplicationIdentifierPrefix', [''])[0]
    if 'tvOS' not in p.get('Platform', []) or not e.get('get-task-allow') or udid not in p.get('ProvisionedDevices', []): continue
    if e.get('application-identifier') not in (prefix + '.*', prefix + '.' + bundle): continue
    if p['ExpirationDate'] < datetime.datetime.now(): continue
    certs = [hashlib.sha1(c).hexdigest().upper() for c in p['DeveloperCertificates']]
    sha = next((c for c in certs if c in ids), None)
    if sha and (best is None or p['ExpirationDate'] > best[2]): best = (path, sha, p['ExpirationDate'], prefix, p['TeamIdentifier'][0])
if not best: sys.exit('no tvOS development profile with an installed identity covers ' + bundle + ' on ' + udid)
print(json.dumps({'profile': best[0], 'identity': best[1], 'prefix': best[3], 'team': best[4]}))
`, udid, appId])) as { profile: string; identity: string; prefix: string; team: string };
await cp(chosen.profile, join(bundle, 'embedded.mobileprovision'));
// The ad-hoc build's entitlements, with the team's identifiers.
const adhoc = sh(['sh', '-c', `codesign -d --entitlements - --xml "${bundle}" 2>/dev/null || true`]);
const entitlements = sh(['python3', '-I', '-c', `
import plistlib, sys
raw = sys.stdin.buffer.read()
e = plistlib.loads(raw) if raw.strip() else {}
prefix, team, app = sys.argv[1], sys.argv[2], sys.argv[3]
e['application-identifier'] = prefix + '.' + app
e['com.apple.developer.team-identifier'] = team
e['get-task-allow'] = True
e['keychain-access-groups'] = [prefix + '.' + app]
sys.stdout.write(plistlib.dumps(e).decode())
`, chosen.prefix, chosen.team, appId], adhoc);
const entitlementsPath = join(scratch, 'tvos-entitlements.plist');
await writeFile(entitlementsPath, entitlements);
// Inside out: every nested framework and dylib, then the app.
const nested = sh(['sh', '-c', `cd "${bundle}" && find . -depth \\( -name '*.framework' -o -name '*.dylib' -o -name '*.appex' \\) -print`]).split('\n').filter(Boolean);
for (const item of nested) sh(['codesign', '--force', '--sign', chosen.identity, '--timestamp=none', join(bundle, item)]);
sh(['codesign', '--force', '--sign', chosen.identity, '--timestamp=none', '--entitlements', entitlementsPath, '--generate-entitlement-der', bundle]);
console.log(`tvos: signed ${bundle} with ${chosen.profile.split('/').at(-1)}`);

// 7. Install, and with --run launch.
const install = Bun.spawnSync(['xcrun', 'devicectl', 'device', 'install', 'app', '--device', udid, bundle], { env, stdout: 'inherit', stderr: 'inherit' });
if (install.exitCode) process.exit(install.exitCode);
if (flag('--run')) {
  const launch = Bun.spawnSync(['xcrun', 'devicectl', 'device', 'process', 'launch', '--device', udid, '--terminate-existing', appId], { env, stdout: 'inherit', stderr: 'inherit' });
  process.exit(launch.exitCode ?? 1);
}
