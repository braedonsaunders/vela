// A holding state replaces the node's overlays too: give each state the node's own hover,
// focus and group looks unless it names its own (the current nav pill keeps its ring).
type Overlays = { hover?: Style; focus?: Style; groupHover?: Style; groupFocus?: Style; active?: Style };
function keepOverlays(n: Node): Node {
  const node = n as Node &
    Overlays & {
      states?: (Overlays & { when: Condition[]; style: Style })[];
      children?: Node[];
      item?: Node;
    };
  const states = node.states?.map(st => ({
    hover: node.hover,
    focus: node.focus,
    groupHover: node.groupHover,
    groupFocus: node.groupFocus,
    active: node.active,
    ...st,
  }));
  return {
    ...node,
    ...(states ? { states } : {}),
    ...(node.children ? { children: node.children.map(keepOverlays) } : {}),
    ...(node.item ? { item: keepOverlays(node.item) } : {}),
  } as Node;
}
const each = <T extends Record<string, Node>>(o: T): T =>
  Object.fromEntries(Object.entries(o).map(([k, v]) => [k, keepOverlays(v)])) as T;

