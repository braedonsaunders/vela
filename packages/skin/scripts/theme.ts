// Writes src/theme.generated.ts: the Tamber theme tokens (client/app.tamber) skin documents name
// by value (`ink.primary`, `var(--cinematic.glass)`). The house value of each token; the
// `pack=installed` variants were Exact's runtime skin packs and do not apply here.
// Run from the repo root: bun packages/skin/scripts/theme.ts
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = join(import.meta.dir, '../../..');
const source = await readFile(join(root, 'client/app.tamber'), 'utf8');
const tokens: Record<string, string> = {};
let inTheme = false;
for (const line of source.split('\n')) {
  if (/^theme\b/.test(line)) { inTheme = true; continue; }
  if (/^\S/.test(line)) { inTheme = false; continue; }
  const match = inTheme && /^  ([A-Za-z][\w.-]*) = (.+?)(\s+scheme=\w+)?\s*$/.exec(line);
  if (match) tokens[match[1]] = match[2];
}
const body = Object.entries(tokens).map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`).join('\n');
await writeFile(join(root, 'packages/skin/src/theme.generated.ts'),
  `// Generated by packages/skin/scripts/theme.ts from client/app.tamber: do not edit.\nexport const THEME: Record<string, string> = {\n${body}\n};\n`);
console.log(`${Object.keys(tokens).length} tokens`);
