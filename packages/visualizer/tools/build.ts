// Builds the native bundle and the shader tables.
//   bun packages/visualizer/tools/build.ts [--scenes ink,tunnel] [--out dir]
// dist/viz-native.js     glrec + host prelude + the framework (UI section left out) + host epilogue: one script for JSC/Hermes
// dist/programs.json     every program the bundle links, captured by running it headless against a recording host
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dir, '..');
const args = process.argv.slice(2);
const opt = (k: string) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : undefined; };
const out = path.resolve(opt('--out') ?? path.join(root, 'dist'));
const only = opt('--scenes')?.split(',');

const fw = path.join(root, 'framework');
const parts = fs.readdirSync(fw).filter(f => /^[1-9]\d_.*\.js$/.test(f) && f !== '95_ui.js' && f !== '11_synth.js').sort()
  .filter(f => {
    if (!only || !/^[3-6]\d_/.test(f)) return true;
    const src = fs.readFileSync(path.join(fw, f), 'utf8'); const m = /scene\(\{\s*id:\s*'([^']+)'/.exec(src);
    return !!m && only.includes(m[1]);
  });
const read = (p: string) => fs.readFileSync(p, 'utf8');
const bundle = [
  '// Generated by packages/visualizer/tools/build.ts. Do not edit.',
  `// Framework parts: ${parts.join(' ')}`,
  read(path.join(root, 'runtime/glrec.js')).replace(/^if \(typeof module.*$/m, ''),
  read(path.join(root, 'runtime/host-prelude.js')).replace(/^'use strict';/, ''),
  read(path.join(root, 'runtime/analyse-split.js')).replace(/^if \(typeof module.*$/m, ''),
  ...parts.map(f => `// ── framework/${f}\n` + read(path.join(fw, f))),
  read(path.join(root, 'runtime/host-epilogue.js')),
].join('\n');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'viz-native.js'), bundle);

// Headless run: link() records each program and answers with the uniforms declared in its sources.
const programs: { vs: string; fs: string }[] = [];
const declared = (src: string) => {
  const T: Record<string, number> = { float: 0x1406, vec2: 0x8B50, vec3: 0x8B51, vec4: 0x8B52, mat3: 0x8B5B, mat4: 0x8B5C, int: 0x1404, sampler2D: 0x8B5E };
  const u: { name: string; type: number; size: number }[] = [];
  for (const m of src.matchAll(/uniform\s+(?:highp\s+|mediump\s+|lowp\s+)?(\w+)\s+([^;]+);/g))
    for (const d of m[2].split(',')) { const a = /(\w+)\s*(?:\[(\d+)\])?/.exec(d.trim()); if (a && T[m[1]]) u.push({ name: a[1], type: T[m[1]], size: a[2] ? +a[2] : 1 }); }
  return u;
};
let words = 0, flushes = 0;
const host: any = {
  width: 1920, height: 1080, dpr: 1, sampleRate: 48000, now: () => performance.now(), log: (s: string) => console.log(s),
  commandBuffer: new ArrayBuffer(16 << 20), freq: new Float32Array(2048).fill(-60), time: new Float32Array(4096),
  link(id: number, vs: string, fsrc: string) {
    programs.push({ vs, fs: fsrc }); const seen = new Set<string>();
    const uniforms = [...declared(vs), ...declared(fsrc)].filter(x => !seen.has(x.name) && seen.add(x.name));
    return { ok: true, uniforms };
  },
  flush(n: number) { words += n; flushes++; },
  canvasImage() { return { id: 0, width: 1, height: 1 }; },
};
const run = new Function('__host', bundle + '\n;return __viz;');
const viz = run(host);
for (let i = 0; i < 200; i++) viz.frame(i * 16.7);          // warms every scene in the bundle
for (let s = 0; s < viz.scenes.length; s++) { viz.setScene(s); for (let i = 0; i < 90; i++) viz.frame(3400 + s * 1600 + i * 16.7); }
const uniq = new Map(programs.map(p => [p.vs + '\u0000' + p.fs, p]));
fs.writeFileSync(path.join(out, 'programs.json'), JSON.stringify([...uniq.values()]));
console.log(`viz-native.js ${(bundle.length / 1024).toFixed(0)} KB, ${viz.scenes.length} scenes (${viz.scenes.map((s: any) => s.id).join(', ')}), ${uniq.size} programs, ${(words / flushes / 1024).toFixed(1)}k words per flush`);
