type Stages = Record<string, { msl: string; compiledEntry?: string }>;

/** Combine independently translated shaders without collisions between their private helpers. */
export function metalLibrary(programs: { stages: Stages }[]): string {
  const includes = new Set<string>();
  const entries = new Set<string>();
  const sections: string[] = [];
  for (const { stages } of programs) for (const stage of Object.values(stages)) {
    const entry = stage.compiledEntry;
    if (!entry || entries.has(entry)) throw new Error('Missing or duplicate Metal entry: ' + entry);
    entries.add(entry);
    const code = stage.msl.replace(/^#include [^\n]+$/gm, include => { includes.add(include); return ''; });
    const exported = code.replace(/^(vertex|fragment) /m, `[[host_name("${entry}")]] $1 `);
    if (exported === code) throw new Error('Missing Metal entry point ' + entry);
    sections.push(`namespace ${entry}_scope {\n${exported}\n}\n`);
  }
  return ['// Generated by packages/visualizer/tools/apple-shaders.ts.', ...includes, ...sections]
    .join('\n').replace(/[ \t]+$/gm, '');
}
