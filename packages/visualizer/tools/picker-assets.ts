// Metro resolves bundled artwork at build time and needs literal require paths.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..');
const scenes: { id: string }[] = JSON.parse(readFileSync(join(root, 'scenes.json'), 'utf8'));
const rows = scenes.map(({ id }) => {
  if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error('Invalid scene ID ' + id);
  readFileSync(join(root, 'thumbnails', id + '.jpg'));
  return `  '${id}': require('./thumbnails/${id}.jpg'),`;
});
writeFileSync(join(root, 'thumbnails.ts'), [
  '// Generated by tools/picker-assets.ts from the release scene manifest.',
  'export const thumbnails: Record<string, number> = {', ...rows, '};', '',
].join('\n'));
