// Vela's Apple native module (tvOS): the native implementations of the views the web
// implements in modules/web/index.js. Contract owns all chrome and every skin; these views
// only bridge what Contract cannot reach on this platform.
//
//   vela-player   the native playback engine (VelaPlayer.swift): originals demuxed on the
//                 device, VideoToolbox video, native or decoded audio, overlay subtitles
//   vela-context  the server origin, the device's media capabilities, network hints
//   vela-preview  muted card previews, played by AVPlayer from broker grants
//   vela-theme    nothing to inject: the web's CSS has no native counterpart (states come
//                 from the focus engine; fonts and images load through the data module)
//   vela-engine   nothing: per-engine hand-off is a web loader concept
//   vela-install  nothing: there is no web-app install on a television
import Foundation
import UIKit

final class Vela: ExactModule {
    override class var views: [String: ExactNativeFactory] {
        [
            "vela-player": ExactNativeFactory(for: Vela.self) { module, props, events in
                try VelaPlayerView(module, props, events)
            },
            "vela-context": ExactNativeFactory { props, events in VelaContextView(props, events) },
            "vela-preview": ExactNativeFactory { props, events in VelaPreviewView(props, events) },
            "vela-theme": ExactNativeFactory { _, events in VelaQuietView(events) },
            "vela-engine": ExactNativeFactory { _, events in VelaQuietView(events) },
            "vela-install": ExactNativeFactory { _, events in VelaQuietView(events) },
        ]
    }
}
let exactModule: ExactModule.Type = Vela.self

/// A view with nothing to draw or report on this platform.
final class VelaQuietView: ExactNativeInstance {
    private let empty: UIView = {
        let view = UIView()
        view.isUserInteractionEnabled = false
        view.isHidden = true
        return view
    }()
    init(_ events: ExactNativeEvents) { super.init(events: events) }
    override var view: ExactNativeView { empty }
}

/// The server this client talks to, the device's media capabilities, and network hints:
/// what the web reads from `location.origin`, codec probes and `navigator.connection`.
final class VelaContextView: ExactNativeInstance {
    private let empty: UIView = {
        let view = UIView()
        view.isUserInteractionEnabled = false
        view.isHidden = true
        return view
    }()
    private var probe = ""

    init(_ props: [String: String], _ events: ExactNativeEvents) {
        super.init(events: events)
        probe = props["probe"] ?? ""
        let probe = self.probe
        DispatchQueue.main.async {
            switch probe {
            case "media": events.message(VelaCapabilities.json())
            case "network": events.message(#"{"saveData":false}"#)
            default: events.message(VelaServer.origin)
            }
        }
    }
    override var view: ExactNativeView { empty }
    override func setProps(_ props: [String: String]) throws {
        // A secure hand-off navigates a browser tab to another origin; a native client keeps its
        // server, and says so as the web host does for a refused destination.
        if let target = props["secureNavigate"], !target.isEmpty {
            events.message(#"{"secureNavigation":"rejected"}"#)
        }
    }
}

/// The Ether this build connects to. A development build names it at build time
/// (VelaOrigin.swift, generated by tools/tvos.ts); `defaults write app.ether.vela vela.origin`
/// overrides it on a device.
enum VelaServer {
    static var origin: String {
        let saved = UserDefaults.standard.string(forKey: "vela.origin") ?? ""
        let scheme = URL(string: saved)?.scheme
        if scheme == "https" || scheme == "http" {
            return saved
        }
        return velaBuildOrigin
    }
}
