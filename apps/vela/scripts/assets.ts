// Writes src/assets.generated.ts: every file a built-in skin document names, bundled with the app
// so documents draw without the network. App assets keep their document path (`assets/grain.svg`);
// a built-in document's own assets keep the URL Ether would serve them at
// (`/vela/v0/appearance/skins/<id>/<version>/<file>`). SVGs arrive as data URIs (svg-transformer.js),
// other files as bundled asset ids. Run: bun apps/vela/scripts/assets.ts
import { readdir } from 'node:fs/promises';
import { join, relative } from 'node:path';

const root = join(import.meta.dir, '../../..');
const out = join(root, 'apps/vela/src/assets.generated.ts');
const entries: [string, string][] = [];
const media = /\.(svg|png|jpe?g|webp|ttf|otf)$/i;

async function walk(dir: string): Promise<string[]> {
  const found: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...await walk(path));
    else if (media.test(entry.name)) found.push(path);
  }
  return found;
}

for (const file of await walk(join(root, 'apps/vela/assets'))) {
  if (file.includes('/icons/')) continue;
  entries.push([`assets/${relative(join(root, 'apps/vela/assets'), file)}`, file]);
}
// Every built-in document with assets of its own, at the id and version the document declares.
const skins = join(root, 'packages/protocol/fixtures/skins');
for (const entry of await readdir(skins, { withFileTypes: true })) {
  if (!entry.isDirectory() || entry.name.startsWith('.')) continue;
  const assets = join(skins, entry.name, 'assets');
  const { default: doc } = await import(join(skins, entry.name, 'document.ts')) as { default: { id: string; version: string } };
  for (const file of await walk(assets).catch(() => [] as string[])) {
    entries.push([`/vela/v0/appearance/skins/${doc.id}/${doc.version}/${relative(assets, file)}`, file]);
  }
}
// The Cinematic document's preview is the app's own picture of it.
entries.push(['/vela/v0/appearance/skins/cinematic-doc/1.0.1/preview.jpg', join(root, 'apps/vela/assets/skins/cinematic.jpg')]);
const lines = entries.map(([key, file]) => `  ${JSON.stringify(key)}: require(${JSON.stringify(relative(join(root, 'apps/vela/src'), file))}),`);
await Bun.write(out, `// Generated by apps/vela/scripts/assets.ts: do not edit.\n/* eslint-disable */\nexport const ASSETS: Record<string, number | string> = {\n${lines.join('\n')}\n};\n`);
console.log(`${entries.length} assets`);
