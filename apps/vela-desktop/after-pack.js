// Without a Developer ID, the macOS app is signed ad hoc so Apple silicon runs it (Gatekeeper still
// asks the viewer to confirm the first open). With CSC_LINK or an identity configured, skip this.
const { execFileSync } = require('node:child_process');
const path = require('node:path');

exports.default = async function afterPack(context) {
  if (context.electronPlatformName !== 'darwin' || process.env.CSC_LINK) return;
  const app = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`);
  execFileSync('codesign', ['--force', '--deep', '--sign', '-', app], { stdio: 'inherit' });
};
